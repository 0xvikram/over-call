import hre from "hardhat";
import fs from "node:fs";
import path from "node:path";

// Deploys OverCall and writes its address + ABI where the web app reads them.
async function main() {
  const game = await hre.viem.deployContract("OverCall");
  const publicClient = await hre.viem.getPublicClient();
  const chainId = await publicClient.getChainId();
  const artifact = await hre.artifacts.readArtifact("OverCall");

  const outDir = path.resolve(__dirname, "../../web/lib/generated");
  fs.mkdirSync(outDir, { recursive: true });
  fs.writeFileSync(
    path.join(outDir, `deployment.${chainId}.json`),
    JSON.stringify({ address: game.address, chainId, network: hre.network.name }, null, 2),
  );
  fs.writeFileSync(
    path.join(outDir, "abi.ts"),
    `// Generated by chain/scripts/deploy.ts\nexport const overCallAbi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n`,
  );
  console.log(`OverCall deployed to ${game.address} on chain ${chainId}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
